"""Reports arriving from the PWA (offline queue flush target).

Telegram reports carry a `tg:<chat>:<message>` id; PWA reports carry a UUID the
browser generated *before* it went offline. That id is the idempotency key: a
flaky connection can replay the same POST any number of times and only one card
is created (RULES §3). The id charset is restricted so it can be used as a file
name without path traversal.
"""

from __future__ import annotations

import base64
import binascii
import re
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field, field_validator

from app.config import Settings
from app.models import Database

CLIENT_ID_RE = re.compile(r"^[A-Za-z0-9_-]{8,64}$")
MAX_CAPTION = 1000
# 1.5 MB decoded ≈ a 2 MB base64 string. A phone photo is usually 1-3 MB, so
# the PWA downscales to 1280 px before queueing; this is the server's backstop.
MAX_PHOTO_BYTES = 1_500_000


class ReportIn(BaseModel):
    client_id: str = Field(description="UUID generated by the PWA before queueing")
    caption: str = Field(min_length=1, max_length=MAX_CAPTION)
    photo_base64: str | None = Field(
        default=None, description="Raw base64 or a data: URL; optional"
    )

    @field_validator("client_id")
    @classmethod
    def _safe_id(cls, value: str) -> str:
        value = value.strip()
        if not CLIENT_ID_RE.match(value):
            raise ValueError("client_id must be 8-64 chars of [A-Za-z0-9_-]")
        return value

    @field_validator("caption")
    @classmethod
    def _clean_caption(cls, value: str) -> str:
        cleaned = " ".join(value.split())
        if not cleaned:
            raise ValueError("caption must not be blank")
        return cleaned


class ReportError(ValueError):
    """The payload was understood but cannot be accepted."""


def _decode_photo(raw: str) -> bytes:
    payload = raw.strip()
    if payload.startswith("data:"):
        _, _, payload = payload.partition(",")
    try:
        data = base64.b64decode(payload, validate=True)
    except (binascii.Error, ValueError) as exc:
        raise ReportError(f"photo_base64 is not valid base64: {exc}") from exc
    if not data:
        raise ReportError("photo_base64 decoded to zero bytes")
    if len(data) > MAX_PHOTO_BYTES:
        raise ReportError(
            f"photo is {len(data) // 1024} KB; the limit is {MAX_PHOTO_BYTES // 1024} KB"
        )
    return data


def store_photo(settings: Settings, client_id: str, data: bytes) -> str:
    """Persist under data_dir/photos; the id is already regex-constrained."""
    photos = Path(settings.data_dir) / "photos"
    photos.mkdir(parents=True, exist_ok=True)
    suffix = ".png" if data.startswith(b"\x89PNG") else ".jpg"
    path = photos / f"pwa-{client_id}{suffix}"
    path.write_bytes(data)
    return str(path)


def create_report(db: Database, settings: Settings, payload: ReportIn) -> tuple[dict[str, Any], bool]:
    """Create (or return) the incident for this client id. Returns (row, created)."""
    report_id = f"pwa:{payload.client_id}"
    existing = db.get_incident_by_report_id(report_id)
    if existing is not None:
        return existing, False

    photo_path = None
    if payload.photo_base64:
        photo_path = store_photo(settings, payload.client_id, _decode_photo(payload.photo_base64))

    incident_id, created = db.create_incident_once(
        report_id=report_id,
        reporter_tg_id=None,
        photo_path=photo_path,
        caption=payload.caption,
    )
    row = db.get_incident(incident_id) or {"id": incident_id}
    return row, created
